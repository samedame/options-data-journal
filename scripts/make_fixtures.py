"""Regenerate tests/fixtures/chain_SYNTHETIC_spy_open.json (deterministic, clearly synthetic).

Usage: python scripts/make_fixtures.py
The chain is Black-Scholes with a put skew - NOT market data, NOT a recording of Yahoo.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

import numpy as np

from odj.snapshot.bs import bs_price

OUT = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "chain_SYNTHETIC_spy_open.json"


def main() -> None:
    now = datetime(2026, 11, 2, 14, 45, tzinfo=UTC)  # 09:45 ET
    spot, r, q = 540.0, 0.04, 0.0125
    rows = []
    for expiry in ("2026-11-04", "2026-11-13", "2026-11-20", "2026-12-18"):
        exp_dt = datetime.fromisoformat(expiry + "T21:00:00+00:00")  # ~16:00 ET
        T = (exp_dt - now).total_seconds() / (365 * 86400)
        for strike in np.arange(480.0, 605.0, 5.0):
            iv = float(np.clip(0.17 - 0.35 * np.log(strike / spot), 0.08, 1.5))
            for right in ("C", "P"):
                mid = float(bs_price(spot, strike, T, r, q, iv, right == "C"))
                half = max(0.02, 0.01 * mid)
                rows.append(
                    {
                        "expiry": expiry,
                        "strike": float(strike),
                        "right": right,
                        "bid": round(max(mid - half, 0.0), 2),
                        "ask": round(mid + half, 2),
                        "last": round(mid, 2),
                        "volume": float(int(abs(strike - spot)) * 7 + 100),
                        "open_interest": float(int(5000 - abs(strike - spot) * 20)),
                        "iv_vendor": round(iv, 5),
                    }
                )
    doc = {
        "_marker": "SYNTHETIC - generated by scripts/make_fixtures.py; not market data",
        "underlying_price": spot,
        "market": {"^VIX": 16.0, "^VIX9D": 15.0, "^VIX3M": 18.0, "^VXN": 20.0, "^IRX": 4.0},
        "options": rows,
    }
    OUT.write_text(json.dumps(doc, indent=1) + "\n")
    print(f"wrote {OUT} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
